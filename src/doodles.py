import math

# ------------------------------------------------------------------ geometry helpers
def C(cx, cy, r, a0=0, a1=360, n=28, ry=None):
    ry = r if ry is None else ry
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def R(x0, y0, x1, y1, r=0.12):
    r = min(r, (x1 - x0) / 2, (y1 - y0) / 2)
    pts = []
    for (cx, cy, a) in [(x1 - r, y0 + r, -90), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90), (x0 + r, y0 + r, 180)]:
        pts += C(cx, cy, r, a, a + 90, 4)
    return pts + [pts[0]]


def P(*pts):
    return list(pts)


def Z(*pts):
    return list(pts) + [pts[0]]


# stroke = (points, fill) ; fill in None | "a" "b" "c" (theme soft colours) | "i" (ink)
def S(pts, f=None):
    return (pts, f)


