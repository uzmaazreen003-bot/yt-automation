_geo = {}


def _prep(name):
    """Resample strokes (so wobble is smooth) and compute lengths."""
    if name in _geo:
        return _geo[name]
    seed = sum(ord(c) for c in name)
    out, total = [], 0.0
    for si, (pts, fill) in enumerate(LIB[name]):
        rs = [pts[0]]
        for a, b in zip(pts, pts[1:]):
            d = math.dist(a, b)
            m = max(1, int(d / 0.1))
            for i in range(1, m + 1):
                rs.append((a[0] + (b[0] - a[0]) * i / m, a[1] + (b[1] - a[1]) * i / m))
        w = []
        for i, (x, y) in enumerate(rs):
            ph = seed + si * 3.1
            w.append((x + 0.012 * math.sin(i * 1.3 + ph), y + 0.012 * math.cos(i * 1.7 + ph * 1.3)))
        L = [0.0]
        for a, b in zip(w, w[1:]):
            L.append(L[-1] + math.dist(a, b))
        out.append((w, fill, L))
        total += L[-1]
    _geo[name] = (out, total)
    return _geo[name]


def draw(ctx, name, cx, cy, size, prog=1.0, ink=None, wobble_t=0.0):
    """size = half-size of the unit box in logical px. prog 0..1 = how much has been drawn."""
    if name not in LIB or prog <= 0 or size < 2:
        return
    th = ctx.th
    ink = ink or th.ink
    fills = {"a": th.soft, "b": th.soft2, "c": th.soft3, "i": ink, None: None}
    strokes, total = _prep(name)
    lw = max(1.6, size * 0.085)
    target = min(1.0, prog) * total
    done = 0.0
    for pts, fill, L in strokes:
        if target <= done:
            break
        take = min(L[-1], target - done)
        done += L[-1]
        full = take >= L[-1] - 1e-6
        # fill appears once the outline is drawn
        pp = []
        for (x, y), l in zip(pts, L):
            if l <= take:
                pp.append((cx + x * size, cy + y * size))
            else:
                break
        if not full and len(pp) < len(pts):
            i = len(pp)
            if i < len(pts):
                a, b = pts[i - 1], pts[i]
                seg = L[i] - L[i - 1]
                f = (take - L[i - 1]) / seg if seg else 0
                pp.append((cx + (a[0] + (b[0] - a[0]) * f) * size, cy + (a[1] + (b[1] - a[1]) * f) * size))
        fc = fills.get(fill)
        if full and fc is not None and len(pp) > 2:
            ctx.poly(pp, fc)
        if len(pp) > 1 and fill != "i":
            ctx.line(pp, ink, lw)
        elif len(pp) > 1:
            ctx.line(pp, ink, lw)
